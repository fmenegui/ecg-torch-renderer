"""Optional offline, true-3D ECG capture with Mitsuba and ray-aligned targets.

This is deliberately separate from the on-device training renderer. Mesh/file
creation, CPU ray tracing and asset decoding happen here. Mitsuba is imported
only when explicitly requested. No downloaded weights or assets are required.
"""
from dataclasses import asdict, dataclass
import hashlib
import math
from pathlib import Path
import tempfile

import numpy as np
import torch
from torch.nn import functional as F
from PIL import Image

from .gpu_appearance import linear_to_srgb
from .gpu_supervision import mask_bounding_boxes


@dataclass(frozen=True)
class PathTraceConfig:
    width: int = 1024
    height: int = 768
    samples_per_pixel: int = 32
    label_samples_per_axis: int = 2
    surface: str = 'fold'
    bend_radians: float = .7
    camera_origin: tuple = (.025, -.115, .38)
    camera_target: tuple = (0., 0., .008)
    field_of_view: float = 48.
    key_radiance: float = 4.
    environment_radiance: float = .12
    background_extent_m: float = 1.5
    occluder: bool = False

    def __post_init__(self):
        for key, low, high in [('width', 64, 4096), ('height', 64, 4096),
                               ('samples_per_pixel', 1, 4096), ('label_samples_per_axis', 1, 4)]:
            value = getattr(self, key)
            if type(value) is not int or not low <= value <= high:
                raise ValueError(f'{key} must be an integer in [{low},{high}]')
        if self.surface not in ('flat', 'curl', 'fold'):
            raise ValueError('surface must be flat, curl or fold')
        for key in ('bend_radians', 'field_of_view', 'key_radiance', 'environment_radiance'):
            if not math.isfinite(getattr(self, key)):
                raise ValueError(f'Finite {key} required')
        if not 0 <= self.bend_radians <= 1.2 or not 10 <= self.field_of_view <= 100:
            raise ValueError('Use bend in [0,1.2] radians and field of view in [10,100] degrees')
        if min(self.key_radiance, self.environment_radiance) < 0:
            raise ValueError('Light radiance must be nonnegative')
        if not math.isfinite(self.background_extent_m) or self.background_extent_m <= 0:
            raise ValueError('Background texture physical extent must be positive and finite')
        if not isinstance(self.occluder, bool):
            raise ValueError('occluder must be a boolean')
        for value in (self.camera_origin, self.camera_target):
            if len(value) != 3 or not np.isfinite(value).all():
                raise ValueError('Camera coordinates must be finite 3-vectors')
        direction = np.asarray(self.camera_target) - np.asarray(self.camera_origin)
        if np.linalg.norm(direction) < 1e-6 or np.linalg.norm(np.cross(direction, [0, 1, 0])) < 1e-6:
            raise ValueError('Nondegenerate camera and up direction required')


def paper_mesh(width_m, height_m, surface='fold', bend_radians=.7, columns=129, rows=65):
    """A developable sheet generated by integrating a unit tangent in meters.

    UV origin is the top left of the canonical bitmap. Cylinder/crease bends
    preserve arc length along x and do not stretch the vertical material axis.
    This is prescribed geometry, not a thin-shell mechanics simulation.
    """
    if not all(math.isfinite(x) and x > 0 for x in (width_m, height_m)):
        raise ValueError('Positive finite physical sheet size required')
    if surface not in ('flat', 'curl', 'fold') or not 0 <= bend_radians <= 1.2:
        raise ValueError('Invalid paper surface or bend')
    if columns < 3 or rows < 2:
        raise ValueError('At least 3 columns and 2 rows required')
    material_x = np.linspace(-width_m/2, width_m/2, columns)
    midpoints = (material_x[:-1]+material_x[1:])*.5
    if surface == 'fold':
        angle = -bend_radians*np.tanh(midpoints/(width_m*.018))
    elif surface == 'curl':
        angle = bend_radians*midpoints/(width_m/2)
    else:
        angle = np.zeros(columns-1)
    dx = width_m/(columns-1)
    # Each discrete edge has exactly dx length. Averaging endpoint tangents
    # would shorten sharp creases and compress printed calibration locally.
    x = np.r_[0., np.cumsum(np.cos(angle)*dx)]
    z = np.r_[0., np.cumsum(np.sin(angle)*dx)]
    x -= (x[0]+x[-1])/2
    z -= z.min()
    z += .00008
    u, v = np.meshgrid(np.linspace(0, 1, columns), np.linspace(0, 1, rows))
    vertices = np.stack((np.broadcast_to(x, u.shape), (.5-v)*height_m,
                         np.broadcast_to(z, u.shape)), -1).reshape(-1, 3)
    uv = np.stack((u, v), -1).reshape(-1, 2)
    a = (np.arange(rows-1)[:, None]*columns+np.arange(columns-1)).ravel()
    faces = np.concatenate((np.stack((a, a+columns, a+1), -1),
                            np.stack((a+1, a+columns, a+columns+1), -1)))
    return vertices.astype(np.float32), uv.astype(np.float32), faces.astype(np.int32)


def _write_obj(path, vertices, uv, faces):
    with Path(path).open('w') as stream:
        for x, y, z in vertices:
            stream.write(f'v {x:.9g} {y:.9g} {z:.9g}\n')
        for u, v in uv:
            stream.write(f'vt {u:.9g} {v:.9g}\n')
        for face in faces+1:
            stream.write('f '+' '.join(f'{index}/{index}' for index in face)+'\n')


def _visible_samples(mi, scene, config, paper_shape):
    """Intersect actual camera rays. Never infer labels from averaged AOV IDs."""
    h, w, count = config.height, config.width, config.label_samples_per_axis
    base_y, base_x = np.mgrid[:h, :w]
    for iy in range(count):
        for ix in range(count):
            x = (base_x+(ix+.5)/count)/w
            y = (base_y+(iy+.5)/count)/h
            position = mi.Point2f(mi.Float(x.astype(np.float32).ravel()),
                                 mi.Float(y.astype(np.float32).ravel()))
            ray, _ = scene.sensors()[0].sample_ray(0., .5, position, mi.Point2f(.5))
            hit = scene.ray_intersect(ray)
            visible = np.asarray((hit.is_valid() & (hit.shape == paper_shape) &
                                  (hit.wi.z > 0)).numpy()).reshape(h, w)
            uv = hit.uv.numpy().T.reshape(h, w, 2)
            # Explicit flip_tex_coords=False matches top-left bitmap indexing.
            field = torch.from_numpy(np.nan_to_num(uv*2-1, nan=2., posinf=2., neginf=2.).copy())[None]
            yield field, torch.from_numpy(visible.astype(np.float32))[None, None]


def pathtrace_capture(canonical, *, config=None, background_texture=None, seed=1973):
    """Render one canonical RenderBatch with 3D light transport and targets.

    Canonical input must be one rectified page, including instance targets.
    Outputs use the same conventions as ECGSupervisionLayer and stay on CPU.
    Targets are geometric coverage from stratified primary rays, not optical
    readability estimates. The optional local background image is decoded as
    sRGB. No asset is downloaded by this function.
    """
    config = config or PathTraceConfig()
    if not isinstance(config, PathTraceConfig):
        raise TypeError('config must be PathTraceConfig')
    if canonical.image.ndim != 4 or canonical.image.shape[0] != 1 or canonical.image.shape[1] != 3:
        raise ValueError('Path tracing requires one canonical image at a time')
    if {'traces', 'instances', 'valid'} - canonical.targets.keys():
        raise ValueError('Render canonical stage=all with return_instances=True')
    if not torch.isfinite(canonical.image).all() or (canonical.image < 0).any() or (canonical.image > 1).any():
        raise ValueError('Canonical RGB must be finite sRGB in [0,1]')
    h, w = canonical.image.shape[-2:]
    for key, channels in [('traces', 12), ('valid', 1), ('instances', None)]:
        value = canonical.targets[key]
        if value.ndim != 4 or value.shape[0] != 1 or value.shape[-2:] != (h, w) or (channels is not None and value.shape[1] != channels):
            raise ValueError(f'Invalid canonical {key} shape')
        if not torch.isfinite(value).all() or (value < 0).any() or (value > 1).any():
            raise ValueError(f'Canonical {key} coverage must be finite in [0,1]')
    count = canonical.targets['instances'].shape[1]
    if count < 1 or canonical.metadata['lead_id'].shape != (1, count) or canonical.metadata['active'].shape != (1, count):
        raise ValueError('Instance identities must match canonical mask slots')
    parameters = canonical.metadata.get('parameters', {})
    for key in ('angle', 'quarter', 'translate_x', 'translate_y', 'perspective_x', 'perspective_y',
                'radial', 'curl_x', 'curl_y', 'crease_warp', 'surface_strength', 'asset_active'):
        if key in parameters and (parameters[key] != 0).any():
            raise ValueError('Input must be a rectified page rendered with photo=False')
    if 'zoom' in parameters and (parameters['zoom'] != 1).any():
        raise ValueError('Input must be a rectified page rendered with photo=False')
    if not isinstance(seed, int) or not 0 <= seed < 2**32:
        raise ValueError('Seed must be an integer in [0,2**32)')
    try:
        import mitsuba as mi
        import drjit as dr
    except ImportError as error:
        raise ImportError('Offline path tracing needs the optional mitsuba dependency') from error
    mi.set_variant('llvm_ad_rgb')
    dr.set_thread_count(2)
    transform = mi.ScalarTransform4f
    ppm = float(canonical.metadata['ppm'][0].detach().cpu())
    if not math.isfinite(ppm) or ppm <= 0:
        raise ValueError('Canonical scale must be positive and finite')
    ch, cw = canonical.image.shape[-2:]
    width_m, height_m = cw/ppm*.001, ch/ppm*.001
    vertices, uv, faces = paper_mesh(width_m, height_m, config.surface, config.bend_radians)
    source = canonical.image.detach().cpu().clamp(0, 1)
    texture = (source[0].permute(1, 2, 0).numpy()*255).round().astype(np.uint8)
    with tempfile.TemporaryDirectory(prefix='ecg-3d-') as temp:
        temp = Path(temp)
        Image.fromarray(texture).save(temp/'paper.png')
        texture_hash = hashlib.sha256((temp/'paper.png').read_bytes()).hexdigest()
        _write_obj(temp/'paper.obj', vertices, uv, faces)
        table_reflectance = {'type': 'rgb', 'value': [.32, .28, .22]}
        background_hash = None
        if background_texture is not None:
            background_texture = Path(background_texture).resolve()
            if not background_texture.is_file():
                raise ValueError('Background texture must be a local image')
            background_hash = hashlib.sha256(background_texture.read_bytes()).hexdigest()
            table_reflectance = {'type': 'bitmap', 'filename': str(background_texture),
                                 'raw': False, 'wrap_mode': 'repeat',
                                 'to_uv': mi.ScalarTransform3f().scale([.9/config.background_extent_m]*2).translate([.17, .21])}
        # The backside has unprinted reflectance. It must not mirror ECG ink.
        front = {'type': 'diffuse', 'reflectance': {'type': 'bitmap',
                  'filename': str(temp/'paper.png'), 'raw': False,
                  'filter_type': 'bilinear', 'wrap_mode': 'clamp'}}
        scene_description = {
            'type': 'scene', 'integrator': {'type': 'path', 'max_depth': 6},
            'sensor': {'type': 'perspective', 'fov': config.field_of_view,
                       'to_world': transform.look_at(origin=config.camera_origin,
                           target=config.camera_target, up=[0, 1, 0]),
                       'sampler': {'type': 'independent', 'sample_count': config.samples_per_pixel},
                       'film': {'type': 'hdrfilm', 'width': config.width, 'height': config.height,
                                'pixel_format': 'rgb', 'rfilter': {'type': 'box'}}},
            'paper': {'type': 'obj', 'filename': str(temp/'paper.obj'),
                      'flip_tex_coords': False,
                      'bsdf': {'type': 'twosided', 'front': front,
                               'back': {'type': 'diffuse', 'reflectance': .93}}},
            'table': {'type': 'rectangle', 'to_world': transform.scale([.45, .45, 1]),
                      'bsdf': {'type': 'roughplastic', 'alpha': .25,
                               'diffuse_reflectance': table_reflectance}},
            'key': {'type': 'rectangle', 'to_world': transform.look_at(
                origin=[-.18, -.14, .38], target=[0, 0, 0], up=[0, 1, 0]).scale([.18, .11, 1]),
                    'emitter': {'type': 'area', 'radiance': config.key_radiance}},
            'environment': {'type': 'constant', 'radiance': config.environment_radiance},
        }
        if config.occluder:
            # Rest the rigid pen on the same side of the developable sheet.
            # A fixed world z would put it below folded paper and erase its
            # intended occlusion. Offset endpoints by the local surface normal.
            row = vertices[:129]
            slope = np.gradient(row[:, 2], row[:, 0])
            endpoints = []
            for x, y in ((.10*width_m/.272, -.09*height_m/.204),
                         (.035*width_m/.272, -.035*height_m/.204)):
                z = np.interp(x, row[:, 0], row[:, 2])
                dz = np.interp(x, row[:, 0], slope)
                normal = np.asarray([-dz, 0., 1.]) / math.sqrt(1+dz*dz)
                endpoints.append((np.asarray([x, y, z])+normal*.003).tolist())
            scene_description['pen'] = {'type': 'cylinder', 'p0': endpoints[0],
                'p1': endpoints[1], 'radius': .003,
                'bsdf': {'type': 'roughplastic', 'alpha': .15,
                         'diffuse_reflectance': {'type': 'rgb', 'value': [.02, .04, .08]}}}
        scene = mi.load_dict(scene_description)
        radiance = np.array(mi.render(scene, seed=seed, spp=config.samples_per_pixel))
        if not np.isfinite(radiance).all():
            raise RuntimeError('Nonfinite path-traced radiance')
        image = linear_to_srgb(torch.from_numpy(radiance).permute(2, 0, 1)[None]).clamp(0, 1)
        paper_shape = next(shape for shape in scene.shapes() if shape.id() == 'paper')
        material_valid = canonical.targets['valid'].detach().cpu().float()
        channels = torch.cat((canonical.targets['traces'].detach().cpu()*material_valid,
                              canonical.targets['instances'].detach().cpu()*material_valid,
                              material_valid), 1).float()
        masks = torch.zeros(1, channels.shape[1], config.height, config.width)
        paper_valid = torch.zeros(1, 1, config.height, config.width)
        for field, visible in _visible_samples(mi, scene, config, paper_shape):
            masks += F.grid_sample(channels, field, padding_mode='border', align_corners=False)*visible
            paper_valid += visible
        samples = config.label_samples_per_axis**2
        masks /= samples
        paper_valid /= samples
    valid = masks[:, -1:]
    # Preserve coverage semantics: source-valid applies once, not squared.
    lead_masks, instance_masks = masks[:, :12], masks[:, 12:-1]
    lead_boxes, lead_box_valid = mask_bounding_boxes(lead_masks)
    instance_boxes, instance_box_valid = mask_bounding_boxes(instance_masks)
    return {'image': image, 'valid': valid, 'paper_mask': paper_valid,
            'lead_masks': lead_masks, 'lead_boxes': lead_boxes, 'lead_box_valid': lead_box_valid,
            'lead_ids': torch.arange(12, dtype=torch.int64)[None],
            'instance_masks': instance_masks, 'instance_boxes': instance_boxes,
            'instance_box_valid': instance_box_valid,
            'instance_lead_ids': canonical.metadata['lead_id'].cpu(),
            'instance_active': canonical.metadata['active'].cpu(),
            'metadata': {'schema': 'ecg-pathtrace-v1', 'mitsuba': mi.__version__, 'variant': mi.variant(),
                         'configuration': asdict(config), 'torch_version': str(torch.__version__),
                         'implementation_sha256': hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
                         'canonical_texture_sha256': texture_hash,
                         'canonical_reference_sha256': hashlib.sha256(canonical.reference.detach().cpu().numpy().astype('<f4').tobytes()).hexdigest(),
                         'canonical_reference_shape': list(canonical.reference.shape),
                         'canonical_reference_dtype': '<f4',
                         'canonical_sample_rate_hz': canonical.metadata.get('sample_rate_hz', torch.tensor([])).detach().cpu().tolist(),
                         'seed': seed, 'samples_per_pixel': config.samples_per_pixel,
                         'label_samples_per_axis': config.label_samples_per_axis,
                         'width_m': width_m, 'height_m': height_m,
                         'surface': config.surface, 'bend_radians': config.bend_radians,
                         'background_sha256': background_hash,
                         'geometry': 'prescribed developable mesh, not cloth dynamics',
                         'external_real_image_validation': False}}
