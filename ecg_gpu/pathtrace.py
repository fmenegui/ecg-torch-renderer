        if config.occluder:
            # Rest the rigid pen above the local sheet profile. A fixed world
            # z could bury it under folded paper and erase its occlusion.
            # A rigid pen contacts the same mesh along its projected length.
            # Lift both endpoints together just enough to avoid intersection.
            sheet = contact_sheet
            contact_rows, contact_columns = sheet.shape[:2]
            def sample_sheet(u, v):
                px, py = u*(contact_columns-1), v*(contact_rows-1)
                ix, iy = min(int(px), contact_columns-2), min(int(py), contact_rows-2)
                fx, fy = px-ix, py-iy
                return ((1-fx)*(1-fy)*sheet[iy, ix]+fx*(1-fy)*sheet[iy, ix+1]+
                        (1-fx)*fy*sheet[iy+1, ix]+fx*fy*sheet[iy+1, ix+1])
            start, end = np.array([.85, .94]), np.array([.63, .67])
